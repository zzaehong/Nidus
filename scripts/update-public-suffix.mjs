// Regenerates src/workspace/public-suffix-list.ts from the Public Suffix List
// (https://publicsuffix.org, Mozilla Public License 2.0).
// Usage: node scripts/update-public-suffix.mjs [public_suffix_list.dat]
// Without a file it downloads the current list. Rules are stored in ASCII (punycode),
// the form hosts reach the Egress Proxy in.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { domainToASCII } from 'node:url';

const source = process.argv[2];
const text = source ? await readFile(source, 'utf8') : await (await fetch('https://publicsuffix.org/list/public_suffix_list.dat')).text();
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? 'unknown';
const commit = text.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? 'unknown';
const rules = new Set();
for (const raw of text.split('\n')) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  const prefix = line.startsWith('!') ? '!' : '';
  const body = prefix ? line.slice(1) : line;
  const wildcard = body.startsWith('*.');
  const ascii = domainToASCII(wildcard ? body.slice(2) : body);
  if (!ascii) throw new Error(`cannot convert rule: ${line}`);
  rules.add(prefix + (wildcard ? '*.' : '') + ascii);
}
const list = [...rules].sort().join(' ');
const out = `// Generated by scripts/update-public-suffix.mjs. Do not edit.
// Public Suffix List ${version}, commit ${commit}, source sha256 ${createHash('sha256').update(text).digest('hex')}.
// https://publicsuffix.org — Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/).
// ICANN and private sections; rules in ASCII form, separated by spaces.
export const PUBLIC_SUFFIX_VERSION = ${JSON.stringify(version)};
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify(list)};
`;
await writeFile(new URL('../src/workspace/public-suffix-list.ts', import.meta.url), out);
console.log(`${rules.size} rules, ${version}`);
