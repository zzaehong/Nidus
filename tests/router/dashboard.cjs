// Run with a separately started preview.py. Only generated fixture credentials are used.
const {chromium} = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');

(async () => {
  const info = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  const browser = await chromium.launch({headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? {channel: process.env.PLAYWRIGHT_CHANNEL} : {})});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:18787');
    await page.locator('#login-token').fill(info.admin);
    await page.locator('#login-form button[type=submit]').click();
    await page.locator('#workspace').waitFor({state: 'visible'});
    await page.locator('[data-page=connections]').click();
    await page.locator('#add-connection').click();
    await page.locator('#connection-name').fill('로컬 검증 연결');
    await page.locator('#connection-provider').selectOption('compatible');
    await page.locator('#connection-url').fill('https://fixture.invalid/v1');
    await page.locator('#connection-key').fill(crypto.randomBytes(24).toString('hex'));
    await page.locator('#connection-form button[type=submit]').click();
    await page.locator('#connection-dialog').waitFor({state: 'hidden'});
    await page.locator('#add-model').click();
    await page.locator('#model-name').fill('무료 분류 모델');
    await page.locator('#model-upstream').fill('fixture-model');
    await page.locator('#model-pricing').selectOption('free');
    await page.locator('#model-form button[type=submit]').click();
    await page.locator('#model-dialog').waitFor({state: 'hidden'});
    await page.locator('[data-page=prompts]').click();
    await page.locator('#system-prompt').fill('입력의 감정을 분류하세요.');
    await page.locator('#output-format').selectOption('json');
    await page.locator('#prompt-form button[type=submit]').click();
    await page.getByText('프롬프트와 응답 설정을 저장했습니다.', {exact: true}).waitFor();
    await page.locator('[data-page=overview]').click();
    await page.locator('#test-input').fill('오늘 정말 즐거웠어');
    await page.locator('#test-form button[type=submit]').click();
    await page.waitForFunction(() => document.getElementById('test-result').textContent.includes('positive'));
    const result = JSON.parse(await page.locator('#test-result').textContent());
    assert.equal(result.output.category, 'positive');
    await page.locator('#notice').evaluate(n => n.hidden = true);
    await page.screenshot({path: '/tmp/nidus-router-dashboard.png', fullPage: true});
    await page.locator('[data-page=records]').click();
    await page.locator('#records-list details').waitFor();
    const log = await page.locator('#records-list pre').textContent();
    assert(!log.includes('오늘 정말 즐거웠어'));
    await page.locator('#store-bodies').check();
    await page.locator('#logging-form button[type=submit]').click();
    await page.getByText('기록 설정을 저장했습니다.', {exact: true}).waitFor();
    await page.locator('[data-page=connections]').click();
    await page.locator('#model-list').getByRole('button', {name: '수정', exact: true}).click();
    await page.locator('#model-override-enabled').check();
    await page.locator('#model-prompt').fill('항상 JSON으로 분류하세요.');
    await page.locator('#model-form button[type=submit]').click();
    await page.locator('#model-dialog').waitFor({state: 'hidden'});
    await page.locator('[data-page=prompts]').click();
    assert((await page.locator('#prompt-previews').textContent()).includes('항상 JSON으로 분류하세요.'));
    await page.locator('[data-page=connections]').click();
    await page.locator('#add-model').click();
    await page.locator('#model-name').fill('유료 검증 모델');
    await page.locator('#model-upstream').fill('paid-fixture');
    await page.locator('#model-pricing').selectOption('paid');
    await page.locator('#model-input-rate').fill('1');
    await page.locator('#model-output-rate').fill('2');
    await page.locator('#model-form button[type=submit]').click();
    await page.locator('#model-dialog').waitFor({state: 'hidden'});
    await page.locator('[data-page=routing]').click();
    await page.locator('#paid-models input').check();
    await page.locator('#monthly-budget').fill('1');
    await page.locator('#budget-form button[type=submit]').click();
    await page.getByText('유료 모델과 월간 예산 승인을 저장했습니다.', {exact: true}).waitFor();
    await page.locator('[data-page=overview]').click();
    await page.locator('#test-model').selectOption({label: '유료 검증 모델'});
    await page.locator('#test-input').fill('유료 모델 검증');
    await page.locator('#test-form button[type=submit]').click();
    await page.waitForFunction(() => document.getElementById('test-result').textContent.includes('positive'));
    assert(JSON.parse(await page.locator('#test-result').textContent()).usage.estimated_cost_usd > 0);
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('[data-page=overview]').click();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({path: '/tmp/nidus-router-mobile.png', fullPage: true});
    assert.deepEqual(errors, []);
    console.log('PASS: browser registration → model → prompt → JSON generation → logs; override; paid approval and budget; mobile layout; no JS errors.');
  } finally {
    await browser.close();
  }
})().catch(e => {console.error(e.message); process.exit(1);});
